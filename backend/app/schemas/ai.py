"""
Pydantic v2 schemas for AI Travel Concierge and Structured Itineraries.
Directly compatible with Google Gemini structured outputs.
"""

import uuid
from typing import List, Optional
from pydantic import Field

from app.schemas.common import BaseSchema


class Activity(BaseSchema):
    time: str = Field(..., description="Time of day, e.g. '09:00 AM' or 'Afternoon'")
    activity: str = Field(..., description="Detailed description of the activity or attraction")
    location: str = Field(..., description="Specific place, landmark, or venue name")
    notes: Optional[str] = Field(None, description="Travel tips, booking requirements, or dress codes")
    estimated_cost: Optional[float] = Field(None, description="Estimated cost for this activity")


class MealSuggestion(BaseSchema):
    meal_type: str = Field(..., description="breakfast, lunch, or dinner")
    suggestion: str = Field(..., description="Recommended restaurant, local stall, or culinary experience")
    recommended_dish: Optional[str] = Field(None, description="Must-try local dish or specialty")


class TripDay(BaseSchema):
    day: int = Field(..., ge=1, description="Day number starting at 1")
    date: str = Field(..., description="Date formatted as YYYY-MM-DD")
    theme: str = Field(..., description="Main theme for the day, e.g. 'Old Town Heritage & Street Food'")
    activities: List[Activity] = Field(default_factory=list, description="Scheduled activities for the day")
    meals: List[MealSuggestion] = Field(default_factory=list, description="Recommended dining options")
    accommodation: Optional[str] = Field(None, description="Hotel or area recommendation for lodging")


class BudgetCategory(BaseSchema):
    category: str = Field(..., description="Category, e.g., Accommodation, Transport, Food, Activities, Contingency")
    estimated_amount: float = Field(..., ge=0, description="Estimated total cost for this category")
    percentage: float = Field(..., ge=0, le=100, description="Percentage of total budget")
    saving_tips: str = Field(..., description="Actionable recommendation to optimize cost in this category")


class StructuredTripPlan(BaseSchema):
    """Complete structured itinerary generated by Gemini API."""
    title: str = Field(..., description="Catchy, descriptive trip title")
    summary: str = Field(..., description="Executive summary of the trip experience")
    destination: str = Field(..., description="Target destination city and country")
    duration_days: int = Field(..., ge=1, description="Total duration in days")
    total_estimated_cost: float = Field(..., ge=0, description="Grand total estimated expense")
    currency: str = Field(default="USD", description="Currency symbol/code, e.g. USD or BDT")
    days: List[TripDay] = Field(..., description="Day-by-day scheduled itinerary")
    budget_breakdown: List[BudgetCategory] = Field(default_factory=list, description="Itemized budget breakdown")
    tips: List[str] = Field(default_factory=list, description="Key logistical, packing, and visa tips")
    safety_and_cultural_advice: List[str] = Field(default_factory=list, description="Cultural etiquette and safety guidelines")
    trip_plan_id: Optional[uuid.UUID] = Field(None, description="Saved database ID when persisted")


class PlanTripRequest(BaseSchema):
    destination: str = Field(..., min_length=2, description="Target city, region, or country (e.g. 'Cox\\'s Bazar' or 'Tokyo')")
    origin: Optional[str] = Field("Dhaka, Bangladesh", description="Departure city")
    start_date: str = Field(..., description="Start date in YYYY-MM-DD format")
    end_date: str = Field(..., description="End date in YYYY-MM-DD format")
    travelers: int = Field(default=1, ge=1, le=50, description="Number of travelers")
    interests: List[str] = Field(
        default_factory=lambda: ["sightseeing", "food", "relaxation"],
        description="Key interests (e.g. culture, food, beaches, adventure, shopping, nature)"
    )
    budget: Optional[float] = Field(None, ge=50, description="Target budget limit")
    currency: str = Field(default="USD", description="Currency (USD, BDT, EUR)")
    travel_style: str = Field(default="mid-range", description="budget, mid-range, luxury, or backpacker")
    save_to_account: bool = Field(default=True, description="Whether to persist the generated plan in user's trip_plans")
